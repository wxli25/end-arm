#!/usr/bin/env python3
"""Export END KEM into a pqm4 checkout.

Creates four flat implementation directories, as pqm4 expects:

    <pqm4>/crypto_kem/end512/ref    portable C kernels (also built on the host for testvectors)
    <pqm4>/crypto_kem/end512/m4     ARMv7E-M DSP kernels (src/armv7em)
    <pqm4>/crypto_kem/end1024/ref
    <pqm4>/crypto_kem/end1024/m4

Usage:  python3 pqm4/export_pqm4.py <path-to-pqm4> [--icount] [--clean]

--icount also installs mupq/crypto_kem/icount_{none,keypair,enc,dec}.c (instruction-count
harness used by pqm4/icount_pqm4.sh; not needed for pqm4's own test/benchmark scripts).

The generated directories are build artefacts of this repository: re-run the script after
changing the sources instead of editing the copies inside pqm4.
"""
import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GLUE = Path(__file__).resolve().parent

COMMON = ["end_params.h", "end_api.h", "end_internal.h", "end_arith.h", "end_tables.h", "poly.h",
          "end_xof.h", "end_codec.c", "end_decode.c", "end_kem.c", "end_keygen.c"]
NTRUGEN = ["ntru.c", "ntru.h", "module_p.c", "module_p.h", "big_integer.c", "big_integer.h",
           "fixed_point.c", "fixed_point.h", "poly_big.c", "ntrugen_poly.h", "param.h"]
KERNELS = ["ntt257.c", "ntt3329.c", "ntt12289.c", "polyvec.c", "baseinv257.c"]
BACKENDS = {"ref": "ref", "m4": "armv7em"}
SIZES = {512: dict(pk=514, sk=3618, ct=384), 1024: dict(pk=1027, sk=7235, ct=832)}

API_H = """/* Generated by end-arm/pqm4/export_pqm4.py -- do not edit. */
#ifndef API_H
#define API_H

#include <stdint.h>

#define CRYPTO_SECRETKEYBYTES  {sk}
#define CRYPTO_PUBLICKEYBYTES  {pk}
#define CRYPTO_CIPHERTEXTBYTES {ct}
#define CRYPTO_BYTES           32
#define CRYPTO_ALGNAME "END-{n}"

int crypto_kem_keypair(uint8_t *pk, uint8_t *sk);
int crypto_kem_enc(uint8_t *ct, uint8_t *ss, const uint8_t *pk);
int crypto_kem_dec(uint8_t *ss, const uint8_t *ct, const uint8_t *sk);

#endif
"""

CONFIG_H = """/* Generated by end-arm/pqm4/export_pqm4.py -- do not edit. */
#ifndef END_CONFIG_H
#define END_CONFIG_H
#define END_N {n}
#define END_PQM4 1                 /* hash through pqm4's mupq/common fips202 (Keccak assembly) */
#define END_RANDOMBYTES_EXTERNAL 1 /* randombytes comes from pqm4 (see pqm4_glue.c) */
#define END_BACKEND_NAME "{backend}"
#endif
"""


def with_config(text):
    """Make a header pick up the generated configuration before anything else."""
    return '#include "end_config.h"\n' + text


def export(pqm4, n, impl, backend):
    dst = pqm4 / "crypto_kem" / ("end%d" % n) / impl
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    for name in COMMON:
        text = (ROOT / "src/common" / name).read_text(encoding="utf-8")
        if name == "end_params.h":
            text = with_config(text)
        (dst / name).write_text(text, encoding="utf-8", newline="\n")
    for name in NTRUGEN:
        text = (ROOT / "src/common/ntrugen" / name).read_text(encoding="utf-8")
        if name == "param.h":
            text = with_config(text)
        (dst / name).write_text(text, encoding="utf-8", newline="\n")
    for name in KERNELS:
        src = ROOT / "src" / backend / name
        if not src.exists():
            src = ROOT / "src/ref" / name
        shutil.copyfile(src, dst / name)
    for extra in (ROOT / "src" / backend).glob("*.h"):
        shutil.copyfile(extra, dst / extra.name)
    shutil.copyfile(GLUE / "pqm4_glue.c", dst / "pqm4_glue.c")
    (dst / "api.h").write_text(API_H.format(n=n, **SIZES[n]), encoding="utf-8", newline="\n")
    (dst / "end_config.h").write_text(CONFIG_H.format(n=n, backend=backend), encoding="utf-8", newline="\n")
    print("exported", dst.relative_to(pqm4), "(%d files)" % len(list(dst.iterdir())))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pqm4", type=Path, help="path to a pqm4 checkout")
    ap.add_argument("--clean", action="store_true", help="remove what this script installed and exit")
    ap.add_argument("--icount", action="store_true", help="install the instruction-count harness into mupq/crypto_kem")
    args = ap.parse_args()
    if not (args.pqm4 / "mupq" / "crypto_kem" / "test.c").exists():
        sys.exit("%s does not look like a pqm4 checkout (run git submodule update --init)" % args.pqm4)
    harness = args.pqm4 / "mupq" / "crypto_kem"
    for n in SIZES:
        scheme = args.pqm4 / "crypto_kem" / ("end%d" % n)
        if args.clean:
            shutil.rmtree(scheme, ignore_errors=True)
            print("removed", scheme)
            continue
        for impl, backend in BACKENDS.items():
            export(args.pqm4, n, impl, backend)
    for src in sorted((GLUE / "icount").iterdir()):
        if args.clean:
            (harness / src.name).unlink(missing_ok=True)
        elif args.icount:
            shutil.copyfile(src, harness / src.name)
    if args.icount and not args.clean:
        print("installed instruction-count harness into", harness.relative_to(args.pqm4))


if __name__ == "__main__":
    main()
