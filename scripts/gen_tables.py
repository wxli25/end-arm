#!/usr/bin/env python3
"""Generate the constant tables used by all backends (src/common/end_tables.h).

NTT mod 257  : 7 layers, twiddle k = 3^brv7(k)           (reference layout, public-key wire format)
NTT mod 3329 : 7 layers, twiddle k = 17^brv7(k)          (same tree as mod 257; used for s~', r*f)
NTT mod 12289: complete NTT, twiddle k = psi^brv_logn(k), psi = 11^((q-1)/(2n))   (used for w*c1)

All Montgomery constants use R = 2^16.
"""
import sys

def brv(x, bits):
    r = 0
    for _ in range(bits):
        r = (r << 1) | (x & 1); x >>= 1
    return r

def order(x, p):
    k = 1; y = x % p
    while y != 1:
        y = y * x % p; k += 1
    return k

def centered(x, p):
    x %= p
    return x - p if x > p // 2 else x

def dump(w, name, vals, per=16):
    w("static const int16_t %s[%d] = {\n" % (name, len(vals)))
    for i in range(0, len(vals), per):
        w(",".join(str(x) for x in vals[i:i + per]) + ",\n")
    w("};\n")

def gen(out):
    w = out.write
    w("/* generated by scripts/gen_tables.py -- do not edit */\n#ifndef END_TABLES_H\n#define END_TABLES_H\n#include <stdint.h>\n\n")
    # ---- 7-layer NTTs (257 and 3329) -------------------------------------
    for p, g in ((257, 3), (3329, 17)):
        assert order(g, p) == 256, (p, g)
        z = [pow(g, brv(k, 7), p) for k in range(128)]
        zi = [pow(x, p - 2, p) for x in z]
        w("/* mod %d: %d^brv7(k), k = 0..127 (k = 0 unused); plain and Montgomery (x2^16, centred) forms */\n" % (p, g))
        dump(w, "end_zetas%d" % p, z)
        dump(w, "end_zetas%d_mont" % p, [centered(x * 65536, p) for x in z])
        dump(w, "end_zetas%d_inv" % p, zi)
        dump(w, "end_zetas%d_inv_mont" % p, [centered(x * 65536, p) for x in zi])
        inv128 = pow(128, p - 2, p)
        w("#define END_INV128_MOD%d %d          /* 128^-1 mod %d */\n" % (p, inv128, p))
        w("#define END_INV128_MONT_MOD%d %d     /* 128^-1 * 2^16 mod %d, centred */\n" % (p, centered(inv128 * 65536, p), p))
        w("#define END_MONT_R2_MOD%d %d         /* 2^32 mod %d */\n" % (p, pow(2, 32, p), p))
        w("#define END_MONT_R_MOD%d %d          /* 2^16 mod %d */\n" % (p, pow(2, 16, p), p))
        w("#define END_QINV16_MOD%d %d          /* -p^-1 mod 2^16 (unsigned) */\n\n" % (p, (-pow(p, -1, 65536)) % 65536))
    # ---- complete NTT mod 12289 ----------------------------------------
    QP = 12289
    g = 11
    assert order(g, QP) == QP - 1
    for n, logn in ((512, 9), (1024, 10)):
        psi = pow(g, (QP - 1) // (2 * n), QP)
        assert order(psi, QP) == 2 * n
        zet = [pow(psi, brv(k, logn), QP) for k in range(n)]
        inv_list = []
        length = 1
        while length < n:
            nb = n // (2 * length)
            for b in range(nb):
                inv_list.append(centered(pow(zet[nb + b], QP - 2, QP) * 65536, QP))
            length *= 2
        ninv = pow(n, QP - 2, QP)
        w("/* n = %d: psi^brv(k) * 2^16 mod 12289 (centred), psi = %d, k = 0..n-1 (k = 0 unused) */\n" % (n, psi))
        dump(w, "end_zetas12289_%d" % n, [centered(x * 65536, QP) for x in zet])
        w("/* inverse twiddles * 2^16 (centred) in consumption order of the GS inverse NTT (len = 1,2,4,...) */\n")
        dump(w, "end_zetas12289_inv_%d" % n, inv_list)
        w("#define END_NINV_MONT12289_%d %d   /* n^-1 * 2^16 mod 12289 (centred) */\n" % (n, centered(ninv * 65536, QP)))
        w("#define END_PSI12289_%d %d\n\n" % (n, psi))
    w("#define END_MONT_R2_MOD12289 %d     /* 2^32 mod 12289 */\n" % (pow(2, 32, QP)))
    w("#define END_MONT_R_MOD12289 %d      /* 2^16 mod 12289 */\n" % (pow(2, 16, QP)))
    w("#define END_QINV16_MOD12289 %d     /* -12289^-1 mod 2^16 (unsigned) */\n" % ((-pow(QP, -1, 65536)) % 65536))
    # ---- misc constants ----------------------------------------------------
    w("#define END_INV257_MOD12289 %d      /* 257^-1 mod 12289 (Garner CRT) */\n" % pow(257, QP - 2, QP))
    w("#define END_INV257_MONT_MOD12289 %d /* 257^-1 * 2^16 mod 12289, centred */\n" % centered(pow(257, QP - 2, QP) * 65536, QP))
    w("#define END_INV_QQP_MOD3329 %d      /* (257*12289)^-1 mod 3329 */\n" % pow(257 * QP, 3329 - 2, 3329))
    w("#define END_INV_QQP_MONT_MOD3329 %d /* (257*12289)^-1 * 2^16 mod 3329, centred */\n" % centered(pow(257 * QP, 3329 - 2, 3329) * 65536, 3329))
    w("#endif\n")

if __name__ == '__main__':
    with open(sys.argv[1], 'w') as fp:
        gen(fp)
    print("wrote", sys.argv[1])
